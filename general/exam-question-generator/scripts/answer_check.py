#!/usr/bin/env python3
"""Compute quiz answers instead of typing them (generic helpers for generated question variants).

Import it from a course's own variants script:
    sys.path.insert(0, '<skill>/scripts'); from answer_check import *

Logic: variables = single lowercase letters, constants w/f (also 1/0), operators ¬ ∧ ∨ ⇒ ⇔
(ASCII also: ! & | -> <->). Precedence ¬ > ∧ > ∨ > ⇒ > ⇔; ⇒ is right-associative.
Truth-table rows go www… first, fff… last (change ROW_ORDER if the course uses 0 first).

CLI checks:
    python3 answer_check.py tt "p ∧ q ⇒ r" pqr       truth-table column
    python3 answer_check.py equiv "p ⇒ q" "¬p ∨ q"   equivalent?
    python3 answer_check.py venn "(A ∩ B) \\ C" ABC  region codes for kind:'venn'
"""
import itertools
import json
import re
import sys
from pathlib import Path

ROW_ORDER = [True, False]
TRUE, FALSE = 'w', 'f'

# ─── logic ───
_ASCII = [('<->', '⇔'), ('->', '⇒'), ('!', '¬'), ('&', '∧'), ('|', '∨'), ('1', 'w'), ('0', 'f')]


def parse(src):
    """Return a function env -> bool for a propositional formula."""
    for a, b in _ASCII:
        src = src.replace(a, b)
    toks = re.findall(r'[a-z]|[¬∧∨⇒⇔()]', src.replace(' ', ''))
    pos = [0]

    def peek():
        return toks[pos[0]] if pos[0] < len(toks) else None

    def take():
        pos[0] += 1
        return toks[pos[0] - 1]

    def atom():
        t = take()
        if t == '¬':
            a = atom()
            return lambda e: not a(e)
        if t == '(':
            x = equ()
            assert take() == ')', src
            return x
        if t in ('w', 'f'):
            return lambda e, v=(t == 'w'): v
        return lambda e, t=t: e[t]

    def chain(sym, sub, fn):
        def level():
            left = sub()
            while peek() == sym:
                take()
                right = sub()
                left = (lambda l, r: lambda e: fn(l(e), r(e)))(left, right)
            return left
        return level

    conj = chain('∧', atom, lambda a, b: a and b)
    disj = chain('∨', conj, lambda a, b: a or b)

    def impl():
        left = disj()
        if peek() == '⇒':
            take()
            right = impl()  # right-associative: p ⇒ q ⇒ r = p ⇒ (q ⇒ r)
            return lambda e: (not left(e)) or right(e)
        return left

    equ = chain('⇔', impl, lambda a, b: a == b)
    f = equ()
    assert pos[0] == len(toks), f'cannot parse: {src}'
    return f


def rows(vars_):
    return [dict(zip(vars_, vals)) for vals in itertools.product(ROW_ORDER, repeat=len(vars_))]


def column(src, vars_='pq'):
    """Truth-table column as a string, e.g. 'wfff' for p ∧ q."""
    f = parse(src)
    return ''.join(TRUE if f(r) else FALSE for r in rows(vars_))


def equiv(a, b, vars_='pqr'):
    return column(a, vars_) == column(b, vars_)


def tautology(src, vars_='pqr'):
    return set(column(src, vars_)) == {TRUE}


def true_rows(src, vars_='pq'):
    """Row labels (e.g. 'wf') where the formula is true – handy for kind:'chips'."""
    f = parse(src)
    return [''.join(TRUE if r[v] else FALSE for v in vars_) for r in rows(vars_) if f(r)]


# ─── sets ───
def fmt_set(s, empty='∅'):
    """Sorted set text in the quiz format: '{1, 2, 5}' (empty set -> '∅')."""
    items = sorted(s, key=lambda x: (str(type(x)), x))
    return '{' + ', '.join(map(str, items)) + '}' if items else empty


def venn_codes(expr, names='ABC'):
    """Region codes for kind:'venn': '110' = in 1st and 2nd set, not in 3rd; '000' = outside.
    expr uses ∩ ∪ \\ and the set names, e.g. '(A ∩ B) \\ C'."""
    py = expr.replace('∩', '&').replace('∪', '|').replace('\\', '-')
    out = []
    for bits in itertools.product([1, 0], repeat=len(names)):
        env = {n: ({0} if b else set()) for n, b in zip(names, bits)}
        if eval(py, {}, env):  # noqa: S307 – own trusted formulas only
            out.append(''.join(map(str, bits)))
    return sorted(out)


def powerset(s):
    s = sorted(s)
    return [set(c) for k in range(len(s) + 1) for c in itertools.combinations(s, k)]


# ─── numbers ───
def mod(a, n):
    """Math-style remainder, never negative for n > 0 (Python % already does this)."""
    return a % n


def inverse(a, n):
    """Multiplicative inverse in ℤ/nℤ, or None if gcd(a, n) ≠ 1."""
    try:
        return pow(a, -1, n)
    except ValueError:
        return None


def to_base(n, b):
    digits = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ'
    if n == 0:
        return '0'
    s = ''
    while n:
        n, r = divmod(n, b)
        s = digits[r] + s
    return s


# ─── writing the generated block ───
def write_block(qfile, questions, tag='generated by a variants script – do not edit by hand'):
    """Replace the // <<GEN-START>> … // <<GEN-END>> block in a questions file (append before '];' if missing)."""
    j = lambda x: json.dumps(x, ensure_ascii=False)
    body = ',\n'.join('{' + ','.join(f'{k}:{j(v)}' for k, v in q.items()) + '}' for q in questions)
    block = f'// <<GEN-START>> {tag}\n{body},\n// <<GEN-END>>\n'
    path = Path(qfile)
    s = path.read_text(encoding='utf-8')
    if '// <<GEN-START>>' in s:
        a = s.index('// <<GEN-START>>')
        b = s.index('// <<GEN-END>>\n') + len('// <<GEN-END>>\n')
        s = s[:a] + block + s[b:]
    else:
        i = s.rindex('];')
        s = s[:i] + block + s[i:]
    path.write_text(s, encoding='utf-8')
    return len(questions)


if __name__ == '__main__':
    cmd, *args = sys.argv[1:] or ['help']
    if cmd == 'tt':
        print(' '.join(column(args[0], args[1] if len(args) > 1 else 'pq')))
    elif cmd == 'equiv':
        print(equiv(args[0], args[1], args[2] if len(args) > 2 else 'pqr'))
    elif cmd == 'venn':
        print(venn_codes(args[0], args[1] if len(args) > 1 else 'ABC'))
    else:
        print(__doc__)
